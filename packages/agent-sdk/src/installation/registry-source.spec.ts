import { renderClientSource, renderRegistrySource } from "./registry-source"
import type { RegistryPackage } from "./registry-source.types"

const CORE: RegistryPackage = {
    lists: [
        { key: "modules", from: "@app/core/modules", name: "MODULES" },
        { key: "blocks", from: "@app/core", name: "coreBlocks" },
        { key: "nodes", from: "@app/core", name: "coreNodes" },
    ],
    renderers: { from: "@app/core/client", name: "coreBlocks" },
}
const PLUGIN: RegistryPackage = {
    lists: [
        { key: "blocks", from: "@app/plugin", name: "blocks" },
        { key: "jobs", from: "@app/plugin", name: "jobs" },
        { key: "entities", from: "@app/plugin", name: "entities" },
    ],
    renderers: { from: "@app/plugin/client", name: "renderers" },
}
const LOGIC_ONLY: RegistryPackage = {
    lists: [{ key: "modules", from: "@app/logic", name: "modules" }],
    renderers: null,
}
const NO_BLOCKS: RegistryPackage = {
    lists: [{ key: "nodes", from: "@app/bare", name: "nodes" }],
    renderers: { from: "@app/bare/client", name: "renderers" },
}

describe("renderRegistrySource", () => {
    it("imports every list statically, one import per package entry, and joins the parts with the literal hash", () => {
        const text = renderRegistrySource([CORE, PLUGIN], "deadbeef")
        expect(text).toContain("// Generated by scripts/build-plugin-registry.mjs")
        expect(text).toContain('import { defineInstallation, type Installation } from "@nivo-lite/agent-sdk/installation"')
        expect(text).toContain('import { MODULES as part0Modules } from "@app/core/modules"')
        expect(text).toContain('import { coreBlocks as part0Blocks, coreNodes as part0Nodes } from "@app/core"')
        expect(text).toContain(
            'import { blocks as part1Blocks, jobs as part1Jobs, entities as part1Entities } from "@app/plugin"',
        )
        expect(text).toContain(
            'defineInstallation([{ modules: part0Modules, blocks: part0Blocks, nodes: part0Nodes }, { blocks: part1Blocks, jobs: part1Jobs, entities: part1Entities }], "deadbeef")',
        )
        expect(text).not.toMatch(/\bimport\(/)
    })

    it("takes a package that exports its plugin as the part itself, and names a package of named lists by its key", () => {
        const whole: RegistryPackage = {
            lists: [
                { key: "plugin", from: "@app/core", name: "corePlugin" },
                { key: "blocks", from: "@app/core", name: "coreBlocks" },
            ],
            renderers: { from: "@app/core/client", name: "coreBlocks" },
        }
        const text = renderRegistrySource([whole, { ...LOGIC_ONLY, key: "logic" }], "ff")
        expect(text).toContain('import { corePlugin as part0Plugin } from "@app/core"')
        expect(text).not.toContain("part0Blocks")
        expect(text).toContain('defineInstallation([part0Plugin, { key: "logic", modules: part1Modules }], "ff")')
        expect(renderClientSource([whole])).toContain('import { coreBlocks as part0Blocks } from "@app/core"')
    })

    it("installs nothing from no packages", () => {
        expect(renderRegistrySource([], "00")).toContain('defineInstallation([], "00")')
    })
})

describe("renderClientSource", () => {
    it("makes a lazy renderer per block of every package that draws, loaded by a static import of its client entry", () => {
        const text = renderClientSource([CORE, LOGIC_ONLY, PLUGIN])
        expect(text).toContain('import { lazyRenderer, type BlockRenderer } from "@nivo-lite/agent-sdk/client"')
        expect(text).toContain('import { coreBlocks as part0Blocks } from "@app/core"')
        expect(text).toContain('import { blocks as part2Blocks } from "@app/plugin"')
        expect(text).toContain('import("@app/core/client").then((loaded) => loaded.coreBlocks)')
        expect(text).toContain('import("@app/plugin/client").then((loaded) => loaded.renderers)')
        expect(text).toContain(
            "[...part0Blocks.map((block) => lazyRenderer(block, load0)), ...part2Blocks.map((block) => lazyRenderer(block, load2))]",
        )
        expect(text).not.toContain("@app/logic")
    })

    it("adds nothing for a package that lists no blocks, though it has a client entry", () => {
        const text = renderClientSource([NO_BLOCKS])
        expect(text).not.toContain("@app/bare")
        expect(text).toContain("export const blocks: ReadonlyArray<BlockRenderer> = []")
    })
})
