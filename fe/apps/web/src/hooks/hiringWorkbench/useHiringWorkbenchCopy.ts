/** Resolves the workbench's static copy once per locale, without translator functions in view props. */
export const useHiringWorkbenchCopy = (): HiringViews["workbenchCopy"] => {
    const t = useTranslations("hiring")
    return useMemo(() => Object.freeze({ ...copyGroup1(t), ...copyGroup2(t), ...copyGroup3(t) }), [t])
}
