/** The GraphQL `bookingBoard` answer as the workbench view types read it: `Maybe` fields become `null`, `sort` and `reminderHours` drop out, `byStatus` folds to a record. */
export const toBookingBoard = (data: BookingBoardType): BookingBoard => ({
    timezone: data.timezone,
    today: data.today,
    nowMs: data.nowMs,
    from: data.from,
    to: data.to,
    settings: settingsOf(data),
    services: data.services.map((service) => ({
        id: service.id,
        name: service.name,
        description: service.description,
        durationMin: service.durationMin,
        bufferMin: service.bufferMin,
        priceVnd: service.priceVnd ?? null,
        resourceKind: service.resourceKind ?? null,
        followupDays: service.followupDays ?? null,
        active: service.active,
    })),
    resources: data.resources.map((resource) => ({
        id: resource.id,
        name: resource.name,
        kind: resource.kind,
        capacity: resource.capacity,
        color: resource.color,
        active: resource.active,
        staffId: resource.staffId ?? null,
    })),
    hours: data.hours.map((row) => ({
        resourceId: row.resourceId,
        weekday: row.weekday,
        start: row.start,
        end: row.end,
    })),
    exceptions: data.exceptions.map((row) => ({
        id: row.id,
        resourceId: row.resourceId ?? null,
        date: row.date,
        closed: row.closed,
        start: row.start ?? null,
        end: row.end ?? null,
        note: row.note,
    })),
    bookings: data.bookings.map(bookingRowMapper()),
    waitlist: data.waitlist.map((item) => ({
        id: item.id,
        customer: item.customer,
        phone: item.phone ?? null,
        service: item.service,
        fromMs: item.fromMs,
        toMs: item.toMs,
        party: item.party,
        status: item.status,
    })),
    staff: data.staff.map((person) => ({ id: person.id, name: person.name })),
    figures: {
        bookingsToday: data.figures.bookingsToday,
        noShowPct30d: data.figures.noShowPct30d ?? null,
        finished30d: data.figures.finished30d,
        utilisationPct: data.figures.utilisationPct ?? null,
        depositsPending: data.figures.depositsPending,
        depositsPendingVnd: data.figures.depositsPendingVnd,
    },
    stats: {
        byResource: data.stats.byResource.map((row) => ({
            resourceId: row.resourceId,
            name: row.name,
            openMin: row.openMin,
            bookedMin: row.bookedMin,
            pct: row.pct,
        })),
        byStatus: Object.fromEntries(data.stats.byStatus.map((row) => [row.status, row.count])),
        noShowPct: data.stats.noShowPct,
        doneRevenueVnd: data.stats.doneRevenueVnd,
        total: data.stats.total,
    },
})

const settingsOf = (data: BookingBoardType): BookingBoard["settings"] => {
    return {
        timezone: data.settings.timezone,
        slotStepMin: data.settings.slotStepMin,
        minLeadMin: data.settings.minLeadMin,
        maxAdvanceDays: data.settings.maxAdvanceDays,
        cancelWindowHours: data.settings.cancelWindowHours,
        depositPct: data.settings.depositPct,
        lateCancelFeePct: data.settings.lateCancelFeePct,
        noShowFeeVnd: data.settings.noShowFeeVnd,
        autoConfirm: data.settings.autoConfirm,
        handoffOrder: data.settings.handoffOrder,
        address: data.settings.address,
        publicEnabled: data.settings.publicEnabled,
        publicSlug: data.settings.publicSlug ?? null,
        publicNote: data.settings.publicNote,
    }
}

const bookingRowMapper = (): ((booking: BookingBoardType["bookings"][number]) => BookingBoard["bookings"][number]) => {
    return (booking) => ({
        id: booking.id,
        customer: booking.customer,
        phone: booking.phone ?? null,
        serviceId: booking.serviceId,
        service: booking.service,
        resourceId: booking.resourceId,
        startMs: booking.startMs,
        endMs: booking.endMs,
        date: booking.date,
        startMin: booking.startMin,
        endMin: booking.endMin,
        startClock: booking.startClock,
        endClock: booking.endClock,
        status: booking.status,
        holdsSlot: booking.holdsSlot,
        party: booking.party,
        priceVnd: booking.priceVnd ?? null,
        depositVnd: booking.depositVnd,
        depositStatus: booking.depositStatus,
        feeVnd: booking.feeVnd,
        checkedIn: booking.checkedIn,
        note: booking.note,
        conflictNote: booking.conflictNote,
        source: booking.source,
        leadId: booking.leadId ?? null,
        reschedules: booking.reschedules,
    })
}
