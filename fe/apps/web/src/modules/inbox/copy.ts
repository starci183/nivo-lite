/** The key of one fixed word of the inbox. */
export type InboxCopyKey = (typeof INBOX_COPY_KEYS)[number]

/** Every fixed word of the inbox, resolved once. */
export type InboxCopy = Readonly<Record<InboxCopyKey, string>>

/** Resolves every fixed word through the translator of the `inbox` catalog. */
export const inboxCopyOf = (t: InboxTranslate): InboxCopy =>
    Object.fromEntries(INBOX_COPY_KEYS.map((key) => [key, t(key)])) as InboxCopy
