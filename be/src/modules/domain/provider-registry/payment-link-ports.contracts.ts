import type { ConnectionRecord } from "@modules/domain/connections"

/**
 * THE PAYMENT-LINK PURPOSE: a hosted payment LINK under the provider's own order code (payOS today, others later). The tools
 * `nivo.tool.payment.link.*` are their own purpose, never merged into `nivo.tool.payment.transfer.create`: a transfer instruction is a QR
 * and account details composed for a bank transfer (a read, nothing created anywhere), a payment link is something the provider CREATES
 * (its own order code, a checkout page, a status that moves), so the two are not substitutable. The words are neutral; a failure is thrown
 * with what it proves (`withProof`: `not_sent` when the request never left, `unknown` when it may have); a refusal the provider answered
 * (`providerRefusal` (a `ProviderRegistryError`)) proves no effect. Its refusals are those of the payment tools (`PAYMENT_TOOL_REFUSALS`).
 */

/** What a payment link is asked for. */
export interface PaymentLinkRequest {
    /** The amount to pay, in VND (a positive integer). */
    readonly amountVnd: number
    /** The text the provider shows and carries as the payment's content. */
    readonly description: string
    /** Where the payer's browser goes after paying. */
    readonly returnUrl: string
    /** Where the payer's browser goes after cancelling. */
    readonly cancelUrl: string
    /** When the link stops being valid, ISO 8601 with an offset, or absent for the provider's own default. */
    readonly expiresAt?: string | undefined
}

/** A payment link as a provider answers a create: only the members the provider's documentation gives. */
export interface PaymentLink {
    /** The provider's id of the link. */
    readonly linkId: string
    /** The provider's own (integer) order code of the link, generated by the adapter. */
    readonly orderCode: number
    /** The https address of the hosted payment page. */
    readonly checkoutUrl: string
    /** The raw QR payload, when the provider gave one. */
    readonly qrPayload?: string | undefined
    /** The amount, in VND. */
    readonly amountVnd: number
    /** The description, as the provider kept it. */
    readonly description: string
    /** The provider's status word of the link. */
    readonly status: string
    /** When the link stops being valid, ISO 8601, as the request asked. */
    readonly expiresAt?: string | undefined
}

/** One payment link, named the way the caller knows it: by the provider's link id or by its order code. */
export type PaymentLinkRef = { readonly linkId: string } | { readonly orderCode: number }

/** A payment link as a provider answers a get or a cancel. */
export interface PaymentLinkState {
    /** The provider's id of the link. */
    readonly linkId: string
    /** The provider's order code of the link. */
    readonly orderCode: number
    /** The amount, in VND. */
    readonly amountVnd: number
    /** The amount paid so far, in VND, when the provider says. */
    readonly amountPaidVnd?: number | undefined
    /** The amount still to pay, in VND, when the provider says. */
    readonly amountRemainingVnd?: number | undefined
    /** The provider's status word of the link. */
    readonly status: string
    /** When the link was created, as the provider printed it. */
    readonly createdAt?: string | undefined
    /** When the link was cancelled (a cancel answer), as the provider printed it. */
    readonly canceledAt?: string | undefined
    /** Why it was cancelled, when the provider says. */
    readonly cancellationReason?: string | undefined
}

/** A provider that creates hosted payment links. */
export interface PaymentLinkPort {
    /** The provider key of the accounts it serves. */
    readonly provider: string
    /**
     * Creates one link on the connection. The adapter generates the provider's order code, so it is called ONCE per tool call key (a replay
     * of the same key is the runner's kept answer): a link that may exist (`unknown` proof) is never created again by itself.
     */
    create(connection: ConnectionRecord, request: PaymentLinkRequest): Promise<PaymentLink>
    /** Reads one link by its id or order code; `providerRefusal` (a `ProviderRegistryError`) `not_found` for one the provider does not hold. */
    get(connection: ConnectionRecord, ref: PaymentLinkRef): Promise<PaymentLinkState>
    /** Cancels one link by its id or order code; a link the provider cannot cancel is `rejected`. */
    cancel(connection: ConnectionRecord, ref: PaymentLinkRef, reason: string | undefined): Promise<PaymentLinkState>
}
