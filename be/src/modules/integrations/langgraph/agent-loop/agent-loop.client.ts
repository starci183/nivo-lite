import type { BaseChatModel } from "@langchain/core/language_models/chat_models"
import { HumanMessage, SystemMessage } from "@langchain/core/messages"
import { Injectable } from "@nestjs/common"
import type { NodeAgentLoop, NodeAgentLoopEnd } from "@nivo-lite/agent-sdk/node"
import { createAgent, type ReactAgent } from "langchain"
import type { AgentLoopModel, AgentLoopOptions, AgentLoops } from "./agent-loop.port"
import { openingTextOf, stepBoundOf, wireToolsOf } from "./loop-frame.policy"
import { stepMiddlewareOf, type InCaller, type StepTally } from "./step-middleware.adapter"
import { toolNamesOf } from "./tool-names.policy"

/** The first user message: the step, then what holds for this try, then the pictures the agent should look at. */
const openingOf = (loop: NodeAgentLoop): HumanMessage => {
    const text = openingTextOf(loop)
    const images = loop.images ?? []
    if (images.length === 0) return new HumanMessage(text)
    return new HumanMessage({
        content: [{ type: "text", text }, ...images.map((url) => ({ type: "image_url", image_url: { url } }))],
    })
}

/** The agent of one run, with its tally. */
export interface StepAgent {
    /** The prebuilt agent. */
    readonly agent: ReactAgent
    /** What the run has come to. */
    readonly tally: StepTally
}

/**
 * The prebuilt agent of one run of a step's agent, with its tally. Laid out for the provider's prompt cache: the system message is
 * the agent's craft and the shop's values (one text, as a string), the tools are the agent's whole set in name order plus `done`
 * and `confused`, written by the loop itself (no schema is generated by the library), and the step is the start of the first user
 * message; so two steps of one agent share everything up to the user message, byte for byte.
 *
 * What the agent is NOT given, on purpose: a second middleware (the built-in ones turn a failure into a message or rewrite turns),
 * a response format (it forces a tool choice and adds its own tools), and a checkpointer. The last is switched off, not left out:
 * left out, an agent run inside a thread node keeps a sub-thread of its own, and when the node starts again it hands back the
 * messages of its earlier run without taking a turn or asking the runner anything.
 *
 * @param loop - The frame and the closures the runner handed over.
 * @param model - The model side.
 * @param built - The client the agent is built over: the model side's own. It is never asked: every turn names the client of its try.
 * @param options - The record of the model turns, when the caller keeps one.
 * @param inCaller - Where the runner's closures and the model side are called.
 * @returns The agent and the tally of its run.
 */
export const stepAgentOf = (
    loop: NodeAgentLoop,
    model: AgentLoopModel,
    built: BaseChatModel,
    options: AgentLoopOptions,
    inCaller: InCaller,
): StepAgent => {
    const names = toolNamesOf(
        loop.tools.map((tool) => tool.name),
        model.wireNames === true,
    )
    const { middleware, tally } = stepMiddlewareOf(loop, model, {
        names,
        record: options.record ?? ((_call, act) => act()),
        inCaller,
    })
    const agent = createAgent({
        model: built,
        tools: wireToolsOf(loop.tools, names).map((tool) => ({ ...tool })),
        systemPrompt: new SystemMessage(loop.instructions),
        middleware: [middleware],
        checkpointer: false,
    })
    return { agent, tally }
}

/** Where the caller of the loop runs: work handed in from inside the agent's graph is done there, one piece at a time. */
interface CallerDesk {
    /** Hands a piece of work to the caller's side and resolves to what it came to. */
    readonly inCaller: InCaller
    /** Does the work handed in, in the order it came, until the desk is closed and empty. Called by the caller itself. */
    readonly serve: () => Promise<void>
    /** Closes the desk: `serve` ends once what was handed in is done. */
    readonly close: () => void
}

/**
 * A desk between the agent's graph and the caller. The library runs each hook inside its own graph, where a call would belong to
 * that inner graph; the engine's record of a node's calls, though, belongs to the node that asked for the loop. So a hook does not
 * call the runner or the model side itself: it hands the work to the desk, and `serve`, which the caller started in its own run,
 * does it there and hands the result back. A piece of work is done alone, never beside another.
 *
 * @returns The desk.
 */
const callerDeskOf = (): CallerDesk => {
    const waiting: Array<() => Promise<void>> = []
    const state = { open: true, wake: (): void => undefined }
    const inCaller: InCaller = (act) =>
        new Promise((resolve, reject) => {
            waiting.push(() => act().then(resolve, reject))
            state.wake()
        })
    const serve = async (): Promise<void> => {
        const job = waiting.shift()
        if (job !== undefined) {
            await job()
            return serve()
        }
        if (!state.open) return
        await new Promise<void>((wake) => {
            state.wake = wake
        })
        return serve()
    }
    return {
        inCaller,
        serve,
        close: () => {
            state.open = false
            state.wake()
        },
    }
}

@Injectable()
/**
 * The loop of a step's agent on LangChain's prebuilt agent: the host side of `NodeHostPorts.agent`. It only moves the model from
 * turn to turn. Every check, the call keys, the refusal shape, the required calls and the output schema stay in the runner's
 * closures; the tries, the deadlines and the metering stay with the model side.
 *
 * The closures and the model side are called where the caller runs, not inside the agent's own graph: a call the caller's engine
 * records (an effect, a tool of the door) is then recorded with the node that asked for the loop, in the order it was made.
 *
 * An error is never hidden: what the model side throws when every try failed, and anything a closure throws, leaves `run` as it
 * was thrown (the library's wrapper is taken off).
 */
export class AgentLoopClient implements AgentLoops {
    /** Takes the turns of one step's agent. */
    async run(loop: NodeAgentLoop, model: AgentLoopModel, options: AgentLoopOptions = {}): Promise<NodeAgentLoopEnd> {
        const built = model.model
        // No AI endpoint: no agent is built and no turn is taken. The model side ends the run with its own error, as it would end
        // the first turn; it never reaches the attempt, which takes nothing if it ever did.
        if (built === undefined) return model.turn(() => Promise.resolve({ turns: 0 }))
        const desk = callerDeskOf()
        const { agent, tally } = stepAgentOf(loop, model, built, options, desk.inCaller)
        const walk = agent
            .invoke({ messages: [openingOf(loop)] }, { recursionLimit: stepBoundOf(loop.maxTurns) })
            .finally(desk.close)
        await Promise.allSettled([walk, desk.serve()])
        // What the model side or a closure rejected with leaves as that very rejection, not as the library's wrapper around it.
        const end = (): NodeAgentLoopEnd => ({ turns: Math.min(tally.turns(), loop.maxTurns) })
        const failed = tally.failed()
        if (failed !== null) return failed.then(end)
        await walk
        return end()
    }
}
