// Generates packages/plugin-registry/src/installed.ts and src/client/blocks.ts (the index.ts files re-export them): the one place that names every installed package.
// `node scripts/build-plugin-registry.mjs` writes them; with `--check` it fails when they are out of date.
// The installed packages are the core package (@nivo-lite/blocks-core) and the plugin packages the root package.json lists under
// `"nivo": { "plugins": ["<package name>", ...] }`: the ONE place a plugin is added to this app. A plugin is resolved by PACKAGE NAME
// from node_modules, so it may be a workspace folder of this repository or a package installed from a registry (another project's
// repository, the local registry, private npm). Every listed plugin must be a root dependency, be installed, say
// `"nivo": { "plugin": true }` in its own package.json and be installed at a version its declared range admits; a root dependency
// marked a plugin that the list leaves out stops the build too. Each such problem stops the generator with its own sentence. A plugin exports ONE value from its root entry, `plugin` (made with definePlugin of
// @nivo-lite/agent-sdk/installation: its modules with their agents, nodes, effects, tools and their words, workflow templates,
// entities, jobs, blocks, messages), and, from "./client", the renderers of its blocks as `renderers` (it then also exports `blocks`).
// A package that exports no `plugin` is read by its named lists modules, blocks, nodes, jobs and entities (each optional) and is
// keyed by its package name without the scope. The core package exports itself the same way, as `corePlugin`.
// The generator joins the parts once (defineInstallation): an id two packages declare stops it, with both owners named.
// The text and the hash lines come from @nivo-lite/agent-sdk/installation (built first: npm run build:modules); this file only reads
// the packages, hashes with node:crypto (the browser bundle holds the literal) and writes.
import fs from "node:fs"
import path from "node:path"
import { createHash } from "node:crypto"
import { createRequire } from "node:module"
import * as prettier from "prettier"

const root = path.resolve(import.meta.dirname, "..")
const require = createRequire(path.join(root, "package.json"))
const registryDir = path.join(root, "packages", "plugin-registry")
const isCheck = process.argv.includes("--check")

const CORE = "@nivo-lite/blocks-core"
const CORE_LISTS = [
    { key: "plugin", from: CORE, name: "corePlugin", isRequired: true },
    { key: "blocks", from: CORE, name: "coreBlocks", isRequired: true },
]
const PLUGIN_KEYS = ["modules", "blocks", "nodes", "jobs", "entities"]

/**
 * What the core package gives the front end besides its block renderers, re-exported by the generated `kit/index.ts` (server-safe, `/kit`) and
 * `client/kit.ts` (React, `/client`) so that the app reads it from the registry and never names the package: the graph views (cards, params, contract views), the
 * fixtures of its modules, the agent message card with its kinds and views, the steps flow, the card scope and the words of its blocks.
 * `all` re-exports every name of an entry, `names` only those listed, `json` a message file under an alias.
 */
const CORE_KIT = [
    { side: "server", from: `${CORE}/graph`, all: true },
    { side: "server", from: `${CORE}/fixtures`, all: true },
    { side: "server", from: CORE, names: ["agentMessageItemOf", "agentMessageKinds"], types: ["AgentMessageItem"] },
    {
        side: "client",
        from: `${CORE}/client`,
        names: ["AgentMessageCard", "CardScopeProvider", "agentMessageViews", "stepsFlowOf", "stepsLegendOf", "stepsStatusLabelsOf"],
        types: ["AgentMessageWords"],
    },
    { side: "server", from: `${CORE}/messages/en.json`, json: "blocksMessagesEn" },
    { side: "server", from: `${CORE}/messages/vi.json`, json: "blocksMessagesVi" },
]

/**
 * The text of a kit file: one re-export line per entry of CORE_KIT on that side. The "server" side is `src/kit/index.ts` (entry
 * `@nivo-lite/plugin-registry/kit`: React-free, importable from server components); the "client" side is `src/client/kit.ts`
 * (entry `/client`, with the renderers of the blocks: React components, imported only from client files).
 */
const renderKitSource = (side) =>
    [
        "// Generated by scripts/build-plugin-registry.mjs. Do not edit: change CORE_KIT of the generator, then run `node scripts/build-plugin-registry.mjs`.",
        ...CORE_KIT.filter((entry) => entry.side === side).map((entry) => {
            if (entry.all) return `export * from ${JSON.stringify(entry.from)}`
            if (entry.json) return `export { default as ${entry.json} } from ${JSON.stringify(entry.from)}`
            const types = (entry.types ?? []).map((name) => `type ${name}`)
            return `export { ${[...entry.names, ...types].join(", ")} } from ${JSON.stringify(entry.from)}`
        }),
        "",
    ].join("\n")

const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"))

/** The package.json of an installed dependency, or null when it is not installed. */
const manifestOf = (name) => {
    const file = path.join(root, "node_modules", ...name.split("/"), "package.json")
    return fs.existsSync(file) ? readJson(file) : null
}

/** The plugin packages of this app, by name in name order: the list of the root package.json, each proven installable. */
const resolvedPlugins = (() => {
    const rootManifest = readJson(path.join(root, "package.json"))
    const { resolvePlugins } = require("@nivo-lite/agent-sdk/installation")
    const semver = require("semver")
    const resolved = resolvePlugins({
        declared: rootManifest.nivo?.plugins,
        dependencies: rootManifest.dependencies ?? {},
        manifestOf,
        satisfies: (version, range) => semver.satisfies(version, range, { includePrerelease: true }),
    })
    if (!resolved.ok) {
        console.error("The plugin registry cannot be generated:")
        for (const problem of resolved.problems) console.error(`  - ${problem}`)
        process.exit(1)
    }
    return resolved.names
})()
const pluginNames = () => resolvedPlugins

/** What a package exports: the lists the generator finds, and whether it has a client entry. */
const loadPackage = (lists, renderers, key) => {
    const present = lists.filter((list) => {
        const isPresent = list.name in require(list.from)
        if (!isPresent && list.isRequired) throw new Error(`${list.from} does not export ${list.name}`)
        return isPresent
    })
    return { ...(key === undefined ? {} : { key }), lists: present.map(({ key, from, name }) => ({ key, from, name })), renderers }
}

/** The key of a plugin that exports named lists: its package name without the scope. */
const keyOfName = (name) => name.slice(name.lastIndexOf("/") + 1)

const corePackage = () => loadPackage(CORE_LISTS, { from: `${CORE}/client`, name: "coreBlocks" })

const pluginPackage = (name) => {
    const renderers = manifestOf(name)?.exports?.["./client"] === undefined ? null : { from: `${name}/client`, name: "renderers" }
    const isWhole = "plugin" in require(name)
    return isWhole
        ? loadPackage(
              [
                  { key: "plugin", from: name, name: "plugin", isRequired: true },
                  { key: "blocks", from: name, name: "blocks", isRequired: false },
              ],
              renderers,
          )
        : loadPackage(
              PLUGIN_KEYS.map((key) => ({ key, from: name, name: key, isRequired: false })),
              renderers,
              keyOfName(name),
          )
}

const packageNames = [CORE, ...pluginNames()]
const packages = [corePackage(), ...pluginNames().map(pluginPackage)]
/** The part of a package: the plugin it exports, or its named lists under its key. */
const partOf = (entry) => {
    const whole = entry.lists.find((list) => list.key === "plugin")
    if (whole !== undefined) return require(whole.from)[whole.name]
    return { key: entry.key, ...Object.fromEntries(entry.lists.map((list) => [list.key, require(list.from)[list.name]])) }
}
const parts = packages.map(partOf)

const { defineInstallation, registryLinesOf, renderClientSource, renderRegistrySource } = require(
    "@nivo-lite/agent-sdk/installation",
)
const registryHash = createHash("sha256").update(registryLinesOf(parts).join("\n")).digest("hex")

// The parts are joined here once, as the generated file joins them at load: an id two packages declare (a module key, a tool, a
// node, a template id or version…) stops the generator, naming the kind, the id and the two plugins.
try {
    defineInstallation(parts, registryHash)
} catch (error) {
    const owners = parts.map((part, index) => `${part.key ?? `part${index}`} = ${packageNames[index]}`).join(", ")
    console.error(`The plugin registry cannot be generated: ${error instanceof Error ? error.message : String(error)}`)
    console.error(`Plugins: ${owners}`)
    process.exit(1)
}

/** The text formatted the way the repository formats TypeScript and JSON. */
const formatted = async (file, text) => {
    const config = (await prettier.resolveConfig(file)) ?? {}
    return prettier.format(text, { ...config, filepath: file })
}

const manifestFile = path.join(registryDir, "package.json")
const manifest = readJson(manifestFile)
const dependencies = Object.fromEntries(
    ["@nivo-lite/agent-sdk", CORE, ...pluginNames()].sort().map((name) => [name, "*"]),
)

const outputs = [
    [path.join(registryDir, "src", "installed.ts"), renderRegistrySource(packages, registryHash)],
    [path.join(registryDir, "src", "client", "blocks.ts"), renderClientSource(packages)],
    [path.join(registryDir, "src", "client", "kit.ts"), renderKitSource("client")],
    [path.join(registryDir, "src", "kit", "index.ts"), renderKitSource("server")],
    [manifestFile, `${JSON.stringify({ ...manifest, dependencies }, null, 2)}\n`],
]

let isStale = false
for (const [file, text] of outputs) {
    const next = await formatted(file, text)
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null
    if (current === next) continue
    isStale = true
    if (!isCheck) {
        fs.mkdirSync(path.dirname(file), { recursive: true })
        fs.writeFileSync(file, next)
    }
    console.log(`${isCheck ? "out of date" : "wrote"} ${path.relative(root, file)}`)
}
if (isCheck && isStale) {
    console.error("The plugin registry is out of date: run node scripts/build-plugin-registry.mjs")
    process.exitCode = 1
}
console.log(`registryHash ${registryHash}`)
